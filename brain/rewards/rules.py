"""
Начальный набор правил наград — то, что засевается в БД при первом запуске.

ДВА КАНАЛА НАГРАДЫ (важно!)
---------------------------
Требование "за повтор награду не давать" нельзя применять ко ВСЕЙ награде:
если обнулить и саму задачу, то бездействие становится выгоднее крафта
(эпизод из 110 шагов стоит -2.2, а достижение цели давало бы +1.0), и агент
честно учится ничего не делать. Поэтому награды разделены:

  1) ЗАДАЧА (per_episode=True) — плотный сигнал "делай дело".
     Затухает ВНУТРИ эпизода: положил палку в слот - награда, вынул и
     положил обратно - почти ноль. Спам-циклы не работают.
     В начале следующего эпизода счётчик сбрасывается: это новая попытка.

  2) НОВИЗНА (сквозное затухание) — именно то, что просил пользователь:
     первый в жизни деревянный меч +40, сотый - копейки; свой счётчик у
     каждого тира, так что каменный/железный награждаются заново.

Итог: агент не может фармить повторы, но и не разучивается работать.

Логика ровно из ТЗ:
  * положил палку в нужный слот меча            -> маленький +
  * положил доску НАД палкой (форма растёт)     -> + побольше
  * собрал форму целиком                        -> ещё больше
  * скрафтил меч                                -> крупная награда
  * скрафтил такой же меч ВТОРОЙ раз            -> награда затухает (decay)
  * каменный / железный / алмазный              -> свои счётчики, всё заново
  * положил не туда / не тот предмет / сломал   -> МИНУС
"""
from __future__ import annotations

from typing import List

from .db import Rule

# --------------------------------------------------------------------------
# Плотные (частые, мелкие) награды за сборку формы
# --------------------------------------------------------------------------
GRID_RULES: List[Rule] = [
    # ВАЖНО про баланс: в сетке 3x3 при случайном тыке примерно 7 клеток из
    # 9 "не те". Если верная укладка стоит +1.0, а ошибка -1.5, то матожидание
    # любой попытки отрицательное, и оптимальной стратегией становится вообще
    # ничего не класть — агент просто бродит по миру. Поэтому верный ход
    # ценится выше ошибки: пробовать должно быть выгодно, ошибаться - нет.
    Rule("grid.place_correct", "grid", per_episode=True,
         base_value=3.0, decay=0.80, min_value=0.1,
         description="Предмет положен в клетку, которая есть в рецепте"),
    Rule("grid.place_adjacent", "spatial", per_episode=True, base_value=1.5, decay=0.80, min_value=0.05,
         description="Пространственная связь верна: предмет примыкает к уже "
                     "выложенной части рецепта (доска НАД палкой и т.п.)"),
    Rule("grid.progress", "grid", per_episode=True, base_value=2.0, decay=0.85, min_value=0.1,
         description="Достигнут новый максимум заполненности формы"),
    Rule("grid.shape_complete", "grid", per_episode=True, base_value=6.0, decay=0.70, min_value=0.25,
         description="Форма рецепта полностью выложена на сетке"),
    # --- штрафы ---
    Rule("grid.place_wrong_cell", "penalty", base_value=-0.4, decay=1.0,
         description="ШТРАФ: предмет положен в клетку, которая в рецепте пуста"),
    Rule("grid.place_wrong_item", "penalty", base_value=-1.2, decay=1.0,
         description="ШТРАФ: в правильную клетку положен неправильный предмет"),
    Rule("grid.break_shape", "penalty", base_value=-2.5, decay=1.0,
         description="ШТРАФ: разрушил уже собранную правильную часть формы"),
    Rule("grid.craft_fail", "penalty", base_value=-1.5, decay=1.0,
         description="ШТРАФ: нажал 'крафт', когда рецепт не собран"),
    Rule("grid.place_no_item", "penalty", base_value=-1.0, decay=1.0,
         description="ШТРАФ: попытка положить предмет, которого нет в руке/инвентаре"),
]

# --------------------------------------------------------------------------
# Награды за сам крафт
# --------------------------------------------------------------------------
CRAFT_RULES: List[Rule] = [
    Rule("craft.planks", "craft", base_value=5.0, decay=0.70, min_value=1.5,
         description="Скрафтил доски"),
    Rule("craft.stick", "craft", base_value=6.0, decay=0.70, min_value=1.5,
         description="Скрафтил палки"),
    Rule("craft.crafting_table", "craft", base_value=14.0, decay=0.60, min_value=2.5,
         description="Скрафтил верстак"),
    Rule("craft.furnace", "craft", base_value=16.0, decay=0.60, min_value=2.5,
         description="Скрафтил печь"),
    # ctx = имя инструмента -> у каждого тира свой счётчик затухания
    Rule("craft.tool", "craft", base_value=25.0, decay=0.60, min_value=4.0,
         description="Скрафтил инструмент (ctx = какой именно). Сквозное "
                     "затухание: 10-й меч того же тира даёт мало, но не ноль"),
    Rule("craft.tool_first_ever", "milestone", base_value=40.0, decay=1.0,
         one_shot=True,
         description="ВЕХА: первый в жизни инструмент этого вида+тира (ctx)"),
    Rule("craft.tier_up", "milestone", base_value=60.0, decay=1.0, one_shot=True,
         description="ВЕХА: агент впервые поднялся на новый тир материала (ctx)"),
    Rule("craft.duplicate_spam", "penalty", base_value=-4.0, decay=1.0,
         description="ШТРАФ: крафтит одно и то же подряд ради фарма награды"),
]

# --------------------------------------------------------------------------
# Мир, движение, ориентация в пространстве
# --------------------------------------------------------------------------
WORLD_RULES: List[Rule] = [
    Rule("world.gather", "craft", per_episode=True,
         base_value=1.5, decay=0.45, min_value=0.0, max_repeats=4,
         description="Добыл нужный ресурс (ctx = что добыл). Лимит выдач: "
                     "копать бесконечно невыгодно, это не цель"),
    # -0.8 за каждый "ненужный" блок = -124 за 60 эпизодов. Но агент не
    # знает заранее, что блок бесполезен — он это и выясняет. Копать надо
    # поощрять, а не штрафовать: оставляем символическую цену.
    Rule("world.gather_useless", "penalty", base_value=-0.15, decay=1.0,
         description="ШТРАФ: добывает мусор, который не нужен ни в одном рецепте"),
    Rule("world.wrong_tool", "penalty", base_value=-2.0, decay=1.0,
         description="ШТРАФ: сломал блок неподходящим инструментом — руда "
                     "уничтожена, дроп не выпал (нужна кирка нужного тира)"),
    # ----------------------------------------------------------------
    # ВЫЖИВАНИЕ.
    #
    # ЗАМЕР (60 эпизодов, wooden_sword, случайная политика) показал перекос:
    # смерть -80 давала -3040 из -4804 всех штрафов, то есть 63%. Против неё
    # 167 очков плюсов — соотношение 1 к 29. При таком раскладе градиент
    # учит одному: не двигайся, тогда не умрёшь. Это не выживание, а паралич.
    #
    # Смерть и так наказана самим обрывом эпизода: агент теряет всю будущую
    # награду. Дублировать это гигантским штрафом не нужно — достаточно
    # сделать её заметно дороже одной цели (-25 против +60 за цель).
    # ----------------------------------------------------------------
    Rule("survival.death", "penalty", base_value=-25.0, decay=1.0,
         description="ШТРАФ: агент погиб — эпизод окончен, прогресс потерян"),
    # hurt был -1.5 за КАЖДЫЙ удар: 420 ударов = -630. Урон и так ведёт к
    # смерти, отдельно наказывать его сильно незачем.
    Rule("survival.hurt", "penalty", base_value=-0.4, decay=1.0,
         description="ШТРАФ: получил урон от моба или опасного блока"),
    Rule("survival.kill", "craft", per_episode=True, base_value=12.0,
         decay=0.75, min_value=2.0,
         description="Убил моба — стало безопаснее, плюс дроп"),
    Rule("survival.hit", "craft", per_episode=True, base_value=1.5,
         decay=0.80, min_value=0.2, max_repeats=8,
         description="Попал по мобу: учим доводить бой до конца"),
    Rule("survival.eat", "craft", per_episode=True, base_value=6.0,
         decay=0.70, min_value=1.0,
         description="Поел вовремя — голод больше не грызёт здоровье"),
    Rule("survival.eat_full", "penalty", base_value=-1.0, decay=1.0,
         description="ШТРАФ: сожрал еду будучи сытым — впустую"),
    Rule("spatial.face_target", "spatial", per_episode=True, base_value=2.0, decay=0.75, min_value=0.05,
         description="Развернулся лицом к нужному блоку/верстаку"),
    Rule("spatial.approach", "spatial", per_episode=True, base_value=1.2, decay=0.80, min_value=0.05,
         description="Сократил дистанцию до цели"),
    # retreat набежал -557 за 928 срабатываний: агент физически обязан
    # иногда отходить (обойти стену, увернуться от моба). Штрафовать надо
    # СИСТЕМАТИЧЕСКОЕ бегство, а не каждый шаг назад, поэтому штраф мелкий
    # и затухающий — первые отходы почти бесплатны, упорное бегство дорожает.
    Rule("spatial.retreat", "penalty", base_value=-0.15, decay=1.0,
         description="ШТРАФ: уходит от цели"),
    Rule("spatial.place_block_correct", "spatial", per_episode=True, base_value=2.0, decay=0.75,
         min_value=0.05,
         description="Поставил блок туда, куда нужно (напр. верстак рядом)"),
    Rule("spatial.wall_bump", "penalty", base_value=-0.5, decay=1.0,
         description="ШТРАФ: упёрся в стену / шаг в никуда"),
    Rule("world.use_table", "spatial", per_episode=True, base_value=3.0, decay=0.70, min_value=0.1,
         description="Открыл верстак, стоя к нему лицом"),
]

# --------------------------------------------------------------------------
# Общая гигиена поведения
# --------------------------------------------------------------------------
BEHAVIOR_RULES: List[Rule] = [
    Rule("behavior.step_cost", "penalty", base_value=-0.02, decay=1.0,
         description="Мелкий штраф за каждый шаг — чтобы не тянул время"),
    Rule("behavior.noop", "penalty", base_value=-0.3, decay=1.0,
         description="ШТРАФ: ничего не делает"),
    Rule("behavior.loop", "penalty", base_value=-1.5, decay=1.0,
         description="ШТРАФ: зациклился (положил-забрал-положил)"),
    Rule("behavior.invalid_action", "penalty", base_value=-1.0, decay=1.0,
         description="ШТРАФ: действие невозможно в текущем состоянии"),
    # ЯКОРЬ ОБУЧЕНИЯ. Затухает, но пол (min_value=25) держится заведомо выше
    # суммарной стоимости эпизода (~110 шагов x 0.02 = 2.2) и любой серии
    # штрафов. Иначе оптимальной стратегией становится бездействие.
    # ЯКОРЬ ОБУЧЕНИЯ. Затухание 0.80 роняло награду до пола за 5 повторов,
    # и дальше цель стоила 25 против -77 накопленных штрафов за эпизод —
    # достигать её было невыгодно. Пол поднят до 40, затухание замедлено:
    # цель обязана оставаться самым выгодным событием в эпизоде ВСЕГДА.
    Rule("goal.completed", "milestone", base_value=60.0, decay=0.92,
         min_value=40.0,
         description="Выполнена текущая цель curriculum (ctx = цель)"),
]

ALL_RULES: List[Rule] = GRID_RULES + CRAFT_RULES + WORLD_RULES + BEHAVIOR_RULES


def seed(db) -> None:
    """Засеять правила в БД (идемпотентно — повторный вызов просто обновит)."""
    db.upsert_many(ALL_RULES)
