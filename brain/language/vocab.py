# Окончания, которые отбрасываются при поиске основы слова. Русский —
# язык падежей: "брёвен", "бревну", "брёвнами" это одно понятие. Полноценная
# морфология тут избыточна, хватает отсечения хвоста.
# Порядок важен: длинные окончания проверяются первыми, иначе "ами"
# обрежется как "и". "ок"/"ек" — беглая гласная ("доска" -> "досок").
_ENDINGS = ("ами", "ями", "ок", "ек", "ов", "ев", "ей", "ен", "ам", "ям",
            "ах", "ях", "ой", "ый", "ий", "ую", "юю", "ом", "ем",
            "у", "ю", "а", "я", "ы", "и", "е", "о", "ь")


def _stem(word: str) -> str:
    """Грубая основа слова: отрезаем известное окончание, если осталось >=4."""
    for end in _ENDINGS:
        if len(word) - len(end) >= 3 and word.endswith(end):
            return word[: -len(end)]
    return word


def _build_stem_index() -> None:
    """
    Строит "основа -> номер токена".

    Кроме обычной основы кладём ещё и укороченную на одну букву: в русском
    бывает беглая гласная ("бревно" -> "брёвен", основы "бревн" и "брев").
    Без этого множественное число не находится.
    """
    for tok, idx in TOKEN_ID.items():
        st = _stem(tok)
        _STEM_INDEX.setdefault(st, idx)
        if len(st) >= 5:
            _STEM_INDEX.setdefault(st[:-1], idx)


def _clean(name: str) -> List[str]:
    """Внутреннее имя в токены: oak_planks -> ['oak', 'planks']."""
    return [p for p in re.split(r"[_\s]+", name.lower()) if p]


