# Обратный индекс: любая форма -> базовое слово.
FORM_TO_BASE: Dict[str, str] = {}
for _base, _forms in FORMS.items():
    for _f in _forms:
        FORM_TO_BASE[_f.replace("ё", "е")] = _base
    FORM_TO_BASE[_base.replace("ё", "е")] = _base


def build_vocab() -> List[str]:
    """Собирает итоговый список токенов. Порядок стабилен между запусками."""
    seen: Dict[str, None] = {}

    def add(tok: str) -> None:
        t = tok.strip().lower()
        if t and t not in seen:
            seen[t] = None

    for t in SPECIAL:
        add(t)
    # Предметная область — по частям, чтобы "oak_log" и "oak_planks"
    # делили общий токен "oak" и сеть видела родство.
    for name in list(ITEMS) + list(BLOCKS) + list(ENTITIES):
        for part in _clean(name):
            add(part)
    # ВАЖНО: из падежных форм в словарь попадает только ПЕРВАЯ (базовая).
    # Раньше "доска", "доски", "досок" получали три разных номера — для
    # сети это были три несвязанных слова. Остальные формы находятся
    # через основу в lookup().
    for d in (RU_ITEMS, RU_TIERS, RU_KINDS, RU_VERBS, RU_QUESTIONS):
        for k, v in d.items():
            kn = k.replace("ё", "е")
            # Пропускаем только падежные формы; базовое слово (оно указывает
            # само на себя) обязано попасть в словарь.
            if FORM_TO_BASE.get(kn, kn) == kn:
                add(k)
            for part in _clean(v):
                add(part)
    # RU_REPLY тоже проверяем по основам: иначе "досок" из реплики получит
    # отдельный номер, хотя "доска" уже добавлена из RU_ITEMS.
    for w in RU_REPLY:
        for part in w.split():
            pn = part.replace("ё", "е")
            # Падежная форма уже представлена базовым словом.
            if FORM_TO_BASE.get(pn, pn) != pn:
                continue
            add(part)
    # Базовые слова из таблицы форм — обязательно, даже если ни в одном
    # словаре выше они не встретились.
    for base in FORMS:
        add(base)
    for n in NUMBERS:
        add(n)
    return list(seen.keys())


VOCAB: List[str] = [t.replace("ё", "е") for t in build_vocab()]
# убрать дубликаты, появившиеся после нормализации ё->е
_seen: Dict[str, None] = {}
for _t in VOCAB:
    _seen.setdefault(_t, None)
VOCAB = list(_seen.keys())
TOKEN_ID: Dict[str, int] = {t: i for i, t in enumerate(VOCAB)}
N_VOCAB: int = len(VOCAB)

# Индекс "основа -> номер токена": строится один раз, чтобы падежные
# формы находились без перебора всего словаря.
_STEM_INDEX: Dict[str, int] = {}

PAD_ID = TOKEN_ID[PAD]
UNK_ID = TOKEN_ID[UNK]
BOS_ID = TOKEN_ID[BOS]
EOS_ID = TOKEN_ID[EOS]


def tokenize(text: str) -> List[str]:
    """Текст в токены. Всё незнакомое станет <unk> на этапе encode."""
    # ё и е — одна буква для нас: "брёвен"/"бревен" не должны различаться.
    text = text.lower().replace("ё", "е")
    return re.findall(r"[а-яa-z0-9_]+", text)


def lookup(tok: str) -> int:
    """
    Номер токена с попыткой подобрать основу.

    Сначала ищем слово целиком, потом его основу, потом основу среди
    основ словаря. Без этого любая падежная форма падала бы в <unk>.
    """
    # Нормализуем здесь тоже: lookup зовут и напрямую, не только после
    # tokenize, и без этого "брёвен" не находило бы "бревно".
    tok = tok.lower().replace("ё", "е")
    # Явная форма — самый надёжный путь, проверяем первым.
    base = FORM_TO_BASE.get(tok)
    if base is not None and base in TOKEN_ID:
        return TOKEN_ID[base]
    if tok in TOKEN_ID:
        return TOKEN_ID[tok]
    st = _stem(tok)
    if st in TOKEN_ID:
        return TOKEN_ID[st]
    cand = _STEM_INDEX.get(st)
    if cand is None and len(st) >= 5:
        cand = _STEM_INDEX.get(st[:-1])
    return cand if cand is not None else UNK_ID


def encode(text: str, max_len: int = 24) -> List[int]:
    """Текст в номера токенов, с обрезкой и добивкой до max_len."""
    ids = [BOS_ID]
    for tok in tokenize(text):
        ids.append(lookup(tok))
        if len(ids) >= max_len - 1:
            break
    ids.append(EOS_ID)
    ids += [PAD_ID] * (max_len - len(ids))
    return ids[:max_len]


def decode(ids: List[int]) -> str:
    """Номера токенов обратно в текст, служебные выбрасываются."""
    out = []
    for i in ids:
        if i in (PAD_ID, BOS_ID, EOS_ID):
            continue
        out.append(VOCAB[i] if 0 <= i < N_VOCAB else UNK)
    return " ".join(out)


